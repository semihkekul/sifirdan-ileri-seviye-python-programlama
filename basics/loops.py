# enumarate
###########################################
tuples = [(1,2), (1,3), (1,4), (2,5)]

for i, t in enumerate(tuples):
    print(i, " -> ", t)
    '''
0  ->  (1, 2)
1  ->  (1, 3)
2  ->  (1, 4)
3  ->  (2, 5)
    '''

