############################################
tuples = [(1,2), (1,3), (1,4), (2,5)]

for tuple in tuples:
    print(tuple)
# (1, 2)
# (1, 3)
# (1, 4)
# (2, 5)

for a,b in tuples:
    print(a, " and ", b)
# 1  and  2
# 1  and  3
# 1  and  4
# 2  and  5

############################################

D = {'k1': 1, 'k2': 2, "k3": 3}

for item in D:
    print(item)

# k1
# k2
# k3    

for item in D.items():
    print(item)
'''
('k1', 1)
('k2', 2)
('k3', 3)
'''

for k, v in D:
    print(k, " -> ", v)
'''
k  ->  1
k  ->  2
k  ->  3
'''

